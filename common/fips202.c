/* =========================================================================
 * Public API — one-shot functions
 * ========================================================================= */

void shake128(uint8_t *out, size_t outlen,
              const uint8_t *in, size_t inlen)
{
    keccak_state state;
    keccak_absorb_once(state.s, SHAKE128_RATE, in, inlen, 0x1f);
    state.pos = 0;
    keccak_squeeze(out, outlen, &state, SHAKE128_RATE);
}

void shake256(uint8_t *out, size_t outlen,
              const uint8_t *in, size_t inlen)
{
    keccak_state state;
    keccak_absorb_once(state.s, SHAKE256_RATE, in, inlen, 0x1f);
    state.pos = 0;
    keccak_squeeze(out, outlen, &state, SHAKE256_RATE);
}

void sha3_256(uint8_t h[32], const uint8_t *in, size_t inlen)
{
    keccak_state state;
    /* SHA-3 uses domain separator 0x06 */
    keccak_absorb_once(state.s, SHA3_256_RATE, in, inlen, 0x06);
    /* Output first 32 bytes of state without permuting (already done) */
    uint8_t buf[SHA3_256_RATE];
    size_t i;
    for (i = 0; i < SHA3_256_RATE / 8; i++) {
        uint64_t lane = state.s[i];
        memcpy(buf + 8 * i, &lane, 8);
    }
    memcpy(h, buf, 32);
}

