/* Round constant bytes (for key schedule) */
static const uint8_t rcon[11] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
};

/* =========================================================================
 * Key expansion
 * ========================================================================= */

static inline uint32_t sub_word(uint32_t w)
{
    return ((uint32_t)sbox[(w >> 24) & 0xff] << 24) |
           ((uint32_t)sbox[(w >> 16) & 0xff] << 16) |
           ((uint32_t)sbox[(w >>  8) & 0xff] <<  8) |
           ((uint32_t)sbox[ w        & 0xff]);
}

static inline uint32_t rot_word(uint32_t w)
{
    return (w << 8) | (w >> 24);
}

void aes_key_expand(aes_ctx *ctx, const uint8_t *key, int key_bytes)
{
    int nk = key_bytes / 4;  /* words in key: 4 (AES-128) or 8 (AES-256) */
    int nr = nk + 6;          /* rounds: 10 or 14                          */
    int i;
    uint32_t *rk = ctx->rk;

    ctx->nr = nr;

    /* Copy key into first nk words */
    for (i = 0; i < nk; i++) {
        rk[i] = ((uint32_t)key[4*i  ] << 24) |
                 ((uint32_t)key[4*i+1] << 16) |
                 ((uint32_t)key[4*i+2] <<  8) |
                  (uint32_t)key[4*i+3];
    }

    /* Expand */
    for (i = nk; i < 4 * (nr + 1); i++) {
        uint32_t t = rk[i - 1];
        if (i % nk == 0)
            t = sub_word(rot_word(t)) ^ ((uint32_t)rcon[i / nk] << 24);
        else if (nk > 6 && i % nk == 4)
            t = sub_word(t);
        rk[i] = rk[i - nk] ^ t;
    }
}

/* =========================================================================
 * AES block encryption
 * ========================================================================= */

/* State is a 4×4 byte matrix stored column-major in 4 uint32_t words */

#define MUL2(x) xtime[(uint8_t)(x)]
#define MUL3(x) ((uint8_t)(MUL2(x) ^ (x)))

/* MixColumns on one column */
static inline uint32_t mix_col(uint32_t w)
{
    uint8_t a0 = (w >> 24), a1 = (w >> 16), a2 = (w >> 8), a3 = w;
    uint8_t r0 = MUL2(a0) ^ MUL3(a1) ^ a2      ^ a3;
    uint8_t r1 = a0      ^ MUL2(a1) ^ MUL3(a2) ^ a3;
    uint8_t r2 = a0      ^ a1      ^ MUL2(a2) ^ MUL3(a3);
    uint8_t r3 = MUL3(a0) ^ a1      ^ a2      ^ MUL2(a3);
    return ((uint32_t)r0 << 24) | ((uint32_t)r1 << 16) |
           ((uint32_t)r2 << 8)  |  (uint32_t)r3;
}

void aes_encrypt_block(const aes_ctx *ctx,
                       uint8_t       out[AES_BLOCK_BYTES],
                       const uint8_t in [AES_BLOCK_BYTES])
{
    const uint32_t *rk = ctx->rk;
    int nr = ctx->nr;
    int r;

    /* Load state in column-major order */
    uint32_t s0, s1, s2, s3, t0, t1, t2, t3;
    s0 = ((uint32_t)in[ 0]<<24)|((uint32_t)in[ 1]<<16)|((uint32_t)in[ 2]<<8)|in[ 3];
    s1 = ((uint32_t)in[ 4]<<24)|((uint32_t)in[ 5]<<16)|((uint32_t)in[ 6]<<8)|in[ 7];
    s2 = ((uint32_t)in[ 8]<<24)|((uint32_t)in[ 9]<<16)|((uint32_t)in[10]<<8)|in[11];
    s3 = ((uint32_t)in[12]<<24)|((uint32_t)in[13]<<16)|((uint32_t)in[14]<<8)|in[15];

    /* Initial round key addition */
    s0 ^= rk[0]; s1 ^= rk[1]; s2 ^= rk[2]; s3 ^= rk[3];
    rk += 4;

    /* Main rounds */
    for (r = 1; r < nr; r++) {
        /* SubBytes + ShiftRows */
        t0 = ((uint32_t)sbox[s0>>24]<<24) | ((uint32_t)sbox[(s1>>16)&0xff]<<16) |
             ((uint32_t)sbox[(s2>> 8)&0xff]<<8) | sbox[s3&0xff];
        t1 = ((uint32_t)sbox[s1>>24]<<24) | ((uint32_t)sbox[(s2>>16)&0xff]<<16) |
             ((uint32_t)sbox[(s3>> 8)&0xff]<<8) | sbox[s0&0xff];
        t2 = ((uint32_t)sbox[s2>>24]<<24) | ((uint32_t)sbox[(s3>>16)&0xff]<<16) |
             ((uint32_t)sbox[(s0>> 8)&0xff]<<8) | sbox[s1&0xff];
        t3 = ((uint32_t)sbox[s3>>24]<<24) | ((uint32_t)sbox[(s0>>16)&0xff]<<16) |
             ((uint32_t)sbox[(s1>> 8)&0xff]<<8) | sbox[s2&0xff];
        /* MixColumns + AddRoundKey */
        s0 = mix_col(t0) ^ rk[0];
        s1 = mix_col(t1) ^ rk[1];
        s2 = mix_col(t2) ^ rk[2];
        s3 = mix_col(t3) ^ rk[3];
        rk += 4;
    }

    /* Final round (no MixColumns) */
    t0 = ((uint32_t)sbox[s0>>24]<<24) | ((uint32_t)sbox[(s1>>16)&0xff]<<16) |
         ((uint32_t)sbox[(s2>> 8)&0xff]<<8) | sbox[s3&0xff];
    t1 = ((uint32_t)sbox[s1>>24]<<24) | ((uint32_t)sbox[(s2>>16)&0xff]<<16) |
         ((uint32_t)sbox[(s3>> 8)&0xff]<<8) | sbox[s0&0xff];
    t2 = ((uint32_t)sbox[s2>>24]<<24) | ((uint32_t)sbox[(s3>>16)&0xff]<<16) |
         ((uint32_t)sbox[(s0>> 8)&0xff]<<8) | sbox[s1&0xff];
    t3 = ((uint32_t)sbox[s3>>24]<<24) | ((uint32_t)sbox[(s0>>16)&0xff]<<16) |
         ((uint32_t)sbox[(s1>> 8)&0xff]<<8) | sbox[s2&0xff];

    t0 ^= rk[0]; t1 ^= rk[1]; t2 ^= rk[2]; t3 ^= rk[3];

    /* Store result */
    out[ 0]=t0>>24; out[ 1]=t0>>16; out[ 2]=t0>>8; out[ 3]=t0;
    out[ 4]=t1>>24; out[ 5]=t1>>16; out[ 6]=t1>>8; out[ 7]=t1;
    out[ 8]=t2>>24; out[ 9]=t2>>16; out[10]=t2>>8; out[11]=t2;
    out[12]=t3>>24; out[13]=t3>>16; out[14]=t3>>8; out[15]=t3;
}

void aes256_ecb(uint8_t       out[AES_BLOCK_BYTES],
                const uint8_t key[AES256_KEY_BYTES],
                const uint8_t in [AES_BLOCK_BYTES])
{
    aes_ctx ctx;
    aes_key_expand(&ctx, key, AES256_KEY_BYTES);
    aes_encrypt_block(&ctx, out, in);
}
